import streamlit as st
import joblib
import numpy as np

# Load model
model = joblib.load("model.pkl")

# Streamlit page configuration
st.set_page_config(
    page_title="Fraudulent Prediction",
    page_icon="🕵🏻"
)

st.title("🕵🏻 Fraudulent Prediction")
st.write("Enter the feature values below to predict whether the transaction is fraudulent.")

# User Inputs
avg_amount_days = st.number_input(
    "Avg_Amount_days",
    min_value=0.0,
    format="%.4f"
)

transaction_amount = st.number_input(
    "Transaction_amount",
    min_value=0.0,
    format="%.4f"
)

is_declined = st.number_input(
    "Is_declined",
    min_value=0.0,
    format="%.4f"
)

number_declines_days = st.number_input(
    "Number_declines_days",
    min_value=0.0,
    format="%.4f"
)

foreign_transaction = st.number_input(
    "Foreign_transaction",
    min_value=0.0,
    format="%.4f"
)

high_risk_countries = st.number_input(
    "High_risk_countries",
    min_value=0.0,
    format="%.4f"
)

daily_chbk_avg_amt = st.number_input(
    "Daily_chbk_avg_amt",
    min_value=0.0,
    format="%.4f"
)

m_avg_chbk_amt = st.number_input(
    "m_avg_chbk_amt",
    min_value=0.0,
    format="%.4f"
)

m_chbk_freq = st.number_input(
    "m_chbk_freq",
    min_value=0.0,
    format="%.4f"
)

# Prediction button
if st.button("Predict Fraudulent"):

    # Create input data
    input_data = np.array([[
        avg_amount_days,
        transaction_amount,
        is_declined,
        number_declines_days,
        foreign_transaction,
        high_risk_countries,
        daily_chbk_avg_amt,
        m_avg_chbk_amt,
        m_chbk_freq
    ]])

    # Prediction
    prediction = model.predict(input_data)

    # Display result
    if prediction[0] == 1:
        st.error("🔴 Fraudulent Transaction")
    else:
        st.success("🟢 Non-Fraudulent Transaction")

